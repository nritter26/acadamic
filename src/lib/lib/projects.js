export const PROJECT_LEVELS = ['beginner', 'intermediate', 'advanced', 'expert'];

export function groupProjectsByDifficulty(projects, filters = {}) {
  const grouped = Object.fromEntries(PROJECT_LEVELS.map(level => [level, []]));

  for (const project of projects) {
    if (filters.difficulty && filters.difficulty !== 'all' && project.difficulty !== filters.difficulty) continue;
    if (filters.language && filters.language !== 'all' && !project.languages?.includes(filters.language)) continue;
    if (filters.framework && filters.framework !== 'all' && project.framework !== filters.framework) continue;
    if (grouped[project.difficulty]) grouped[project.difficulty].push(project);
  }

  return grouped;
}

export async function loadProjectCatalogStream(onProject, onComplete) {
  // Try NDJSON streaming first (progressive load), fall back to bulk endpoint
  try {
    const response = await fetch('/api/content/projects', {
      headers: { 'Accept': 'application/x-ndjson' },
    });
    const contentType = response.headers.get('content-type') || '';
    if (response.ok && contentType.includes('x-ndjson')) {
      const total = parseInt(response.headers.get('X-Total-Projects') || '0', 10);
      const reader = response.body.getReader();
      const decoder = new TextDecoder();
      let buffer = '';
      let loaded = 0;

      while (true) {
        const { done, value } = await reader.read();
        if (done) break;

        buffer += decoder.decode(value, { stream: true });
        const lines = buffer.split('\n');
        buffer = lines.pop() || '';

        for (const line of lines) {
          if (line.trim()) {
            try {
              const project = JSON.parse(line);
              loaded++;
              onProject(project, loaded, total);
            } catch {
              // Skip malformed lines
            }
          }
        }
      }

      onComplete(loaded, total);
      return total;
    }
  } catch {
    // NDJSON failed, fall through to bulk
  }

  // Fallback: load all projects via bulk JSON endpoint (single request, no rate-limit risk)
  try {
    const bulkResponse = await fetch('/api/content/projects');
    if (bulkResponse.ok) {
      const projects = await bulkResponse.json();
      if (Array.isArray(projects)) {
        const total = projects.length;
        for (let i = 0; i < total; i++) {
          onProject(projects[i], i + 1, total);
        }
        onComplete(total, total);
        return total;
      }
    }
  } catch {
    // Bulk also failed
  }

  onComplete(0, 0);
  return 0;
}
